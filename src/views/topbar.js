/* ════════════════════════════════════════════════════════════════════════
   modules/topbar.js —— 顶栏交互（L5 feature）
   ────────────────────────────────────────────────────────────────────────
   重构前这段代码长这样（modules/shell-4.js，全文只有一行）：

       $('quoteBar').onclick = nextQuote;

   就这一行，是**全仓库唯一一处真正的顺序敏感代码** ——
   它在文件被加载的那一刻就去抓 DOM 元素。所以它必须排在 shell.head.html
   之后、且所有含 nextQuote 的文件之后，位置被死死钉在 .module-order.json
   的最后一行。为了这一行，代价是整个 shell 层被切成 4 个碎片
   （shell.js / shell-2 / shell-3 / shell-4）。

   现在它变成一条生命周期注册：

       K.ready(() => { ... })

   于是：
     · 不再需要"排在最后" —— 顺序无关了，shell 层可以合并成一个文件
     · 表达的是真实意图：「DOM 就绪之后做这件事」，而不是「我恰好排在最后」

   这就是「顺序即依赖」这条铁律被打破的标志性一刻。
   ════════════════════════════════════════════════════════════════════════ */

/* 顶栏金句：点一下换一句 */
K.ready(() => {
  const bar = $('quoteBar');
  if (bar) bar.onclick = nextQuote;
});