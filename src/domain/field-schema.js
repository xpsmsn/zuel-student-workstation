function normalizeKey(h){
  const k = String(h == null ? '' : h).trim();
  if(FIELD_ALIASES[k]) return FIELD_ALIASES[k];
  // 表头单元格里常有换行或多余空格（如「学号/␊职工号」）→ 去掉所有空白再试一次
  const squashed = k.replace(/\s+/g, '');
  return FIELD_ALIASES[squashed] || k;
}

