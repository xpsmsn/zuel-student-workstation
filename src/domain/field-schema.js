/* 「提前毕业」的判定 —— 用**相对口径**：该生的预计毕业年份早于本批最常见的那个年份。
   为什么不用「≤ 今年+1」那种绝对口径：它会随年份漂移（到了 2028 年，「≤ 2029」会把整批人
   都算进来，预设就失去意义）。相对口径语义稳定："比同批人早毕业"。
   真实数据（189 行）：2028×188、2027×1 → 命中那 1 人。 */
function gradYearOf(s){
  const m = String((s && s['预计毕业年份']) == null ? '' : s['预计毕业年份']).match(/\d{4}/);
  return m ? parseInt(m[0], 10) : NaN;
}
function batchGradYear(list){
  const c = {};
  (list || []).forEach(s=>{ const y = gradYearOf(s); if(!isNaN(y)) c[y] = (c[y] || 0) + 1; });
  let best = NaN, bestN = 0;
  Object.keys(c).forEach(k=>{ if(c[k] > bestN){ bestN = c[k]; best = parseInt(k, 10); } });
  return best;
}
function isEarlyGrad(s){
  const y = gradYearOf(s), mode = batchGradYear(S.students);   // 基准取**整批**，不取当前筛选后的列表
  return !isNaN(y) && !isNaN(mode) && y < mode;
}
