/* ════════════════════════════════════════════════════════════════════════
   features/reset.js —— 清空全部数据
   ────────────────────────────────────────────────────────────────────────
   原先这个文件叫 features/password.js，里面一半是改密码、一半是清空数据。
   锁屏与密码已于 2026-10-03 整体取消（用户要求），
   只留下「清空数据」这一件仍然需要的事 —— 它就该叫自己的名字。

   ⚠️ 这里用的是**软清空**：写回一张空批次表，而不是删掉存储键。
      删 key 的话，下次启动 boot() 会以为从未使用过，又把演示数据灌回来 ——
      那是老版本栽过的坑（「清空后又冒出 80 条假数据」）。
   ════════════════════════════════════════════════════════════════════════ */

function resetAll() {
  askConfirm({
    title: '清空全部数据', danger: true, okText: '清空全部数据',
    html: `确定<b>清空全部本地数据</b>？<br><br>清空后将回到空白状态（不会自动生成演示数据），<b>此操作不可撤销</b>。<br>如只是想重导一批数据，请到「批次管理」删除单个批次（可撤销）。`,
    onOk() {
      S.batches = []; S.activeBatchId = null; S.students = []; S.grades = []; invalidateGradeMap();
      S.filters = {}; S.quickView = 'all'; S.classFilter = 'all'; S._search = '';
      save();
      location.reload();
    }
  });
}
